import Foundation

/// The Gradle project that builds an app's APK or App Bundle (`Plan.md`
/// §8.5): an `:app` module made from the bundle, and the host's shell,
/// player and contract modules from AndroidAppRuntime's `Android/`
/// directory. Generated in
/// the work directory and reused between builds; `android-app gradle` leaves
/// it for Android Studio.
public struct GradleProject {

    /// How the release build is signed. The passwords come from
    /// `ANDROID_KEYSTORE_PASSWORD` and `ANDROID_KEY_PASSWORD` (the keystore's
    /// by default) when Gradle runs, so they're never in the project.
    public struct Signing: Equatable, Sendable {
        public var keystore: URL
        public var alias: String

        public init(keystore: URL, alias: String) {
            self.keystore = keystore
            self.alias = alias
        }
    }

    /// What Gradle builds.
    public enum Output: String, CaseIterable, Sendable {
        case debugAPK = "debug"
        case releaseAPK = "release"
        case bundle = "aab"

        /// The Gradle task.
        public var task: String {
            switch self {
            case .debugAPK: ":app:assembleDebug"
            case .releaseAPK: ":app:assembleRelease"
            case .bundle: ":app:bundleRelease"
            }
        }

        /// Where the task writes it, in the project.
        public var path: String {
            switch self {
            case .debugAPK: "app/build/outputs/apk/debug/app-debug.apk"
            case .releaseAPK: "app/build/outputs/apk/release/app-release.apk"
            case .bundle: "app/build/outputs/bundle/release/app-release.aab"
            }
        }

        public var fileExtension: String {
            self == .bundle ? "aab" : "apk"
        }
    }

    public var directory: URL

    /// AndroidAppRuntime's checkout: its `Android/` has the shell, the player
    /// and the Gradle wrapper.
    public var hostPackage: URL

    public var bundle: UniversalBundle

    public var signing: Signing?

    /// The ABIs the app has libraries for. Dependencies may bring libraries
    /// for others (androidx's graphics library does), which would let a
    /// device of another ABI install an app without `libapp.so`.
    public var abis: [AndroidABI]

    /// `compileSdk`.
    public static let compileSDK = 36

    public init(directory: URL, hostPackage: URL, bundle: UniversalBundle, abis: [AndroidABI], signing: Signing? = nil) {
        self.directory = directory
        self.hostPackage = hostPackage
        self.bundle = bundle
        self.abis = abis
        self.signing = signing
    }

    public var minSDK: Int {
        max(bundle.minSDK ?? AndroidABI.minimumAPI, AndroidABI.minimumAPI)
    }

    public var targetSDK: Int {
        bundle.targetSDK ?? Validator.defaultTargetSDK
    }

    var app: URL {
        directory.appendingPathComponent("app")
    }

    var main: URL {
        app.appendingPathComponent("src/main")
    }

    /// `jniLibs/<abi>/`, where the packager stages each ABI's libraries.
    public var jniLibs: URL {
        main.appendingPathComponent("jniLibs")
    }

    var android: URL {
        hostPackage.appendingPathComponent("Android")
    }

    // MARK: Files

    var settings: String {
        """
        // Generated by android-app for \(bundle.info.identifier): the app's module and
        // the host's shell, player and contracts, from AndroidAppRuntime.
        pluginManagement {
            repositories {
                google()
                mavenCentral()
                gradlePluginPortal()
            }
        }

        dependencyResolutionManagement {
            repositoriesMode.set(RepositoriesMode.FAIL_ON_PROJECT_REPOS)
            repositories {
                google()
                mavenCentral()
            }
        }

        rootProject.name = \(kotlinString(bundle.info.identifier))
        include(":app")
        include(":appruntime-ui")
        project(":appruntime-ui").projectDir = file(\(kotlinString(android.appendingPathComponent("appruntime-ui").path)))
        include(":appruntime-contracts")
        project(":appruntime-contracts").projectDir = file(\(kotlinString(android.appendingPathComponent("appruntime-contracts").path)))
        include(":appruntime-shell")
        project(":appruntime-shell").projectDir = file(\(kotlinString(android.appendingPathComponent("appruntime-shell").path)))

        """
    }

    var appBuild: String {
        let info = bundle.info
        var signingConfig = ""
        var releaseSigning = ""
        if let signing {
            signingConfig = """

                signingConfigs {
                    create("release") {
                        storeFile = file(\(kotlinString(signing.keystore.path)))
                        keyAlias = \(kotlinString(signing.alias))
                        storePassword = System.getenv("ANDROID_KEYSTORE_PASSWORD")
                        keyPassword = System.getenv("ANDROID_KEY_PASSWORD") ?: System.getenv("ANDROID_KEYSTORE_PASSWORD")
                    }
                }

            """
            releaseSigning = "\n            signingConfig = signingConfigs.getByName(\"release\")"
        }
        return """
            // Generated by android-app from \(bundle.url.lastPathComponent).
            import org.jetbrains.kotlin.gradle.dsl.JvmTarget

            plugins {
                id("com.android.application")
                id("org.jetbrains.kotlin.android")
            }

            android {
                namespace = \(kotlinString(info.identifier))
                compileSdk = \(Self.compileSDK)

                defaultConfig {
                    applicationId = \(kotlinString(info.identifier))
                    minSdk = \(minSDK)
                    targetSdk = \(targetSDK)
                    versionCode = \(Validator.versionCode(info.build) ?? 1)
                    versionName = \(kotlinString(info.version.isEmpty ? info.build : info.version))
                    ndk {
                        abiFilters += listOf(\(abis.map { kotlinString($0.rawValue) }.joined(separator: ", ")))
                    }
                }
            \(signingConfig)
                buildTypes {
                    release {
                        isMinifyEnabled = true
                        proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")\(releaseSigning)
                    }
                }

                compileOptions {
                    sourceCompatibility = JavaVersion.VERSION_17
                    targetCompatibility = JavaVersion.VERSION_17
                }

                packaging {
                    // The Swift libraries are staged as built; Gradle doesn't strip them.
                    jniLibs.keepDebugSymbols += "**/*.so"
                }
            }

            kotlin {
                compilerOptions {
                    jvmTarget.set(JvmTarget.JVM_17)
                }
            }

            dependencies {
                implementation(project(":appruntime-shell"))
            }

            """
    }

    static let proguardRules = """
        # Generated by android-app. The shell's own rules keep what Swift calls
        # by name; these are for its dependencies.
        -dontwarn org.jetbrains.annotations.**

        """

    /// Writes the project, leaving files that haven't changed alone so builds
    /// stay incremental. The libraries go in `jniLibs` separately.
    public func write() throws(PackagerError) {
        let manifest = ManifestWriter(bundle: bundle)
        try write(settings, to: directory.appendingPathComponent("settings.gradle.kts"))
        try copy(android.appendingPathComponent("build.gradle.kts"), to: directory.appendingPathComponent("build.gradle.kts"))
        try copy(android.appendingPathComponent("gradle.properties"), to: directory.appendingPathComponent("gradle.properties"))
        for path in ["gradlew", "gradlew.bat", "gradle/wrapper/gradle-wrapper.jar", "gradle/wrapper/gradle-wrapper.properties"] {
            try copy(android.appendingPathComponent(path), to: directory.appendingPathComponent(path))
        }
        try write(appBuild, to: app.appendingPathComponent("build.gradle.kts"))
        try write(Self.proguardRules, to: app.appendingPathComponent("proguard-rules.pro"))
        try write(manifest.manifest, to: main.appendingPathComponent("AndroidManifest.xml"))

        // Resources: replaced whole, so a language or icon the app dropped goes.
        let res = main.appendingPathComponent("res")
        try remove(res)
        for (folder, text) in manifest.strings {
            try write(text, to: res.appendingPathComponent("\(folder)/strings.xml"))
        }
        if let icon = bundle.icon {
            // Android scales the largest density down for the others.
            try copy(icon, to: res.appendingPathComponent("mipmap-xxxhdpi/ic_launcher.png"))
        }

        // Assets: the app's keys and its resources, which the host reads.
        let rt = main.appendingPathComponent("assets/rt")
        try remove(rt)
        try copy(bundle.url.appendingPathComponent("Info.plist"), to: rt.appendingPathComponent("Info.plist"))
        if let resources = bundle.resources {
            try copy(resources, to: rt.appendingPathComponent("resources"))
        }
    }

    // MARK: Building

    /// Runs Gradle for `output`; the file it made. `androidSwiftUI` is the
    /// checkout with composeui's sources.
    public func build(_ output: Output, androidSwiftUI: URL, toolchain: Toolchain, runner: CommandRunning) throws(PackagerError) -> URL {
        if output != .debugAPK, signing == nil {
            throw PackagerError("a release build needs a keystore: pass --keystore and --alias")
        }
        var environment = toolchain.gradleEnvironment
        environment["ANDROIDSWIFTUI_PATH"] = androidSwiftUI.path
        try runner.run([directory.appendingPathComponent("gradlew").path, "-p", directory.path, "-q",
                        "-PandroidSwiftUIPath=\(androidSwiftUI.path)", output.task],
                       directory: directory, environment: environment)
        let built = directory.appendingPathComponent(output.path)
        guard FileManager.default.fileExists(atPath: built.path) else {
            throw PackagerError("Gradle didn't write \(built.path)")
        }
        return built
    }

    // MARK: Helpers

    private func write(_ text: String, to url: URL) throws(PackagerError) {
        if (try? String(contentsOf: url, encoding: .utf8)) == text {
            return
        }
        do {
            try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
            try text.write(to: url, atomically: true, encoding: .utf8)
        } catch {
            throw PackagerError("can't write \(url.path): \(error)")
        }
    }

    /// Copies a file or directory, keeping its permissions (`gradlew` is
    /// executable).
    private func copy(_ source: URL, to destination: URL) throws(PackagerError) {
        let files = FileManager.default
        do {
            if files.fileExists(atPath: destination.path) {
                if !isDirectory(source), files.contentsEqual(atPath: source.path, andPath: destination.path) {
                    return
                }
                try files.removeItem(at: destination)
            }
            try files.createDirectory(at: destination.deletingLastPathComponent(), withIntermediateDirectories: true)
            try files.copyItem(at: source, to: destination)
        } catch {
            throw PackagerError("can't copy \(source.path) to \(destination.path): \(error)")
        }
    }

    private func remove(_ url: URL) throws(PackagerError) {
        guard FileManager.default.fileExists(atPath: url.path) else { return }
        do {
            try FileManager.default.removeItem(at: url)
        } catch {
            throw PackagerError("can't remove \(url.path): \(error)")
        }
    }

    private func isDirectory(_ url: URL) -> Bool {
        var directory: ObjCBool = false
        return FileManager.default.fileExists(atPath: url.path, isDirectory: &directory) && directory.boolValue
    }
}

/// A Kotlin string literal for `value`.
func kotlinString(_ value: String) -> String {
    var escaped = ""
    for character in value {
        switch character {
        case "\\": escaped += "\\\\"
        case "\"": escaped += "\\\""
        case "$": escaped += "\\$"
        case "\n": escaped += "\\n"
        case "\r": escaped += "\\r"
        case "\t": escaped += "\\t"
        default: escaped.append(character)
        }
    }
    return "\"\(escaped)\""
}
